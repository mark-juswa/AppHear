package com.example.apphear

import com.example.apphear.pipeline.features.CausalConfig
import com.example.apphear.pipeline.features.NormalizeConfig
import com.example.apphear.pipeline.features.clipFeaturesCausal
import com.example.apphear.pipeline.features.clipFeaturesRealtimed
import com.example.apphear.pipeline.recognition.Handedness
import com.example.apphear.pipeline.recognition.SessionNormalizer
import com.google.gson.JsonArray
import com.google.gson.JsonObject
import com.google.gson.JsonParser
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.InputStreamReader
import kotlin.math.abs

/**
 * F18 skew test - the train/serve-parity gate. Feeds the Kotlin S4 port the SAME raw landmarks +
 * span the offline Python pipeline used, and asserts it reproduces the 258-vector within tolerance.
 * Golden vectors are generated by `python -m pipeline.features.export_golden`. A pure JVM test:
 * runs on `gradlew testDebugUnitTest`, no device needed. Failure here = on-device features would
 * drift from training -> recognition degrades; nothing ships until this is green.
 */
class S4SkewTest {

    private fun load(): JsonObject {
        val stream = javaClass.getResourceAsStream("/golden/s4_golden.json")
            ?: error("missing /golden/s4_golden.json - run `python -m pipeline.features.export_golden`")
        return JsonParser.parseReader(InputStreamReader(stream, Charsets.UTF_8)).asJsonObject
    }

    /** Flatten a JSON number array; JSON null (exported for absent landmarks) -> Float.NaN. */
    private fun floats(arr: JsonArray): FloatArray = FloatArray(arr.size()) {
        val e = arr[it]
        if (e.isJsonNull) Float.NaN else e.asFloat
    }

    private fun frames(flat: FloatArray, cols: Int): Array<FloatArray> {
        val rows = flat.size / cols
        return Array(rows) { r -> flat.copyOfRange(r * cols, r * cols + cols) }
    }

    @Test
    fun kotlinS4MatchesPythonWithinTolerance() {
        val root = load()
        val tol = root["tolerance"].asDouble.toFloat()
        val c = root.getAsJsonObject("config")
        val cfg = NormalizeConfig(
            n1Scale = c["n1_scale"].asBoolean,
            n2Roll = c["n2_roll"].asBoolean,
            n3Handedness = c["n3_handedness"].asBoolean,
            handednessEpsilon = c["handedness_epsilon"].asDouble,
        )

        val clips = root.getAsJsonArray("clips")
        assertTrue("no golden clips", clips.size() > 0)

        var worstDiff = 0f
        for (ci in 0 until clips.size()) {
            val clip = clips[ci].asJsonObject
            val id = clip["clip_id"].asString
            val onset = clip["onset"].asInt
            val release = clip["release"].asInt

            val hands = frames(floats(clip.getAsJsonObject("hands_image").getAsJsonArray("data")), 126)
            val pose = frames(floats(clip.getAsJsonObject("pose_image").getAsJsonArray("data")), 132)
            val expected = frames(floats(clip.getAsJsonObject("expected_feature").getAsJsonArray("data")), 258)

            val (actual, params) = clipFeaturesRealtimed(hands, pose, onset, release, cfg)

            assertEquals("[$id] frame count", expected.size, actual.size)

            // params parity (scale/roll are the derived normalization constants)
            val ep = clip.getAsJsonObject("params")
            assertEquals("[$id] scale", ep["scale"].asDouble, params.scale, 1e-4)
            assertEquals("[$id] roll", ep["roll_angle"].asDouble, params.rollAngle, 1e-4)
            assertEquals("[$id] dominant", ep["dominant"].asString, params.dominant)
            assertEquals("[$id] mirrored", ep["mirrored"].asBoolean, params.mirrored)

            for (t in expected.indices) {
                for (k in 0 until 258) {
                    val d = abs(actual[t][k] - expected[t][k])
                    if (d > worstDiff) worstDiff = d
                    assertTrue(
                        "[$id] feature diff $d > $tol at frame $t chan $k " +
                            "(kotlin=${actual[t][k]} python=${expected[t][k]})",
                        d <= tol,
                    )
                }
            }
        }
        println("S4 skew test: ${clips.size()} clips, worst |Kotlin-Python| = $worstDiff (tol=$tol)")
    }

    /**
     * F19a causal skew test - the STREAMING S4 parity gate. Same landmarks + span, but each frame's
     * scale/roll/mirror are estimated from PAST frames only. Kotlin `clipFeaturesCausal` must
     * reproduce Python `clip_features_causal` byte-for-byte, or on-device streaming features drift.
     */
    @Test
    fun kotlinCausalS4MatchesPythonWithinTolerance() {
        val root = load()
        val tol = root["tolerance"].asDouble.toFloat()
        val c = root.getAsJsonObject("config")
        val cfg = NormalizeConfig(
            n1Scale = c["n1_scale"].asBoolean,
            n2Roll = c["n2_roll"].asBoolean,
            n3Handedness = c["n3_handedness"].asBoolean,
            handednessEpsilon = c["handedness_epsilon"].asDouble,
        )
        val cc = root.getAsJsonObject("causal_config")
        val ccfg = CausalConfig(
            mirrorDecisiveMargin = cc["mirror_decisive_margin"].asDouble,
            mirrorMinAbsDiff = cc["mirror_min_abs_diff"].asDouble,
            mirrorConfirmK = cc["mirror_confirm_k"].asInt,
        )

        val clips = root.getAsJsonArray("clips")
        assertTrue("no golden clips", clips.size() > 0)

        var worstDiff = 0f
        for (ci in 0 until clips.size()) {
            val clip = clips[ci].asJsonObject
            val id = clip["clip_id"].asString
            val onset = clip["onset"].asInt
            val release = clip["release"].asInt
            val hands = frames(floats(clip.getAsJsonObject("hands_image").getAsJsonArray("data")), 126)
            val pose = frames(floats(clip.getAsJsonObject("pose_image").getAsJsonArray("data")), 132)
            val expected =
                frames(floats(clip.getAsJsonObject("causal_expected_feature").getAsJsonArray("data")), 258)

            val actual = clipFeaturesCausal(hands, pose, onset, release, cfg, ccfg)
            assertEquals("[$id] causal frame count", expected.size, actual.size)

            for (t in expected.indices) {
                for (k in 0 until 258) {
                    val d = abs(actual[t][k] - expected[t][k])
                    if (d > worstDiff) worstDiff = d
                    assertTrue(
                        "[$id] causal feature diff $d > $tol at frame $t chan $k " +
                            "(kotlin=${actual[t][k]} python=${expected[t][k]})",
                        d <= tol,
                    )
                }
            }
        }
        println("causal S4 skew test: ${clips.size()} clips, worst |Kotlin-Python| = $worstDiff (tol=$tol)")
    }
    /**
     * Deployed S4 parity guard. The app does not call clipFeaturesCausal directly; it uses the
     * session-level wrapper. Starting from a clean session and feeding only the sign span must match
     * the causal golden path exactly, because the estimator window is identical in that regime.
     */
    @Test
    fun deployedSessionNormalizerMatchesCausalS4OnCleanSpan() {
        val root = load()
        val tol = root["tolerance"].asDouble.toFloat()
        val c = root.getAsJsonObject("config")
        val cfg = NormalizeConfig(
            n1Scale = c["n1_scale"].asBoolean,
            n2Roll = c["n2_roll"].asBoolean,
            n3Handedness = c["n3_handedness"].asBoolean,
            handednessEpsilon = c["handedness_epsilon"].asDouble,
        )
        val cc = root.getAsJsonObject("causal_config")
        val ccfg = CausalConfig(
            mirrorDecisiveMargin = cc["mirror_decisive_margin"].asDouble,
            mirrorMinAbsDiff = cc["mirror_min_abs_diff"].asDouble,
            mirrorConfirmK = cc["mirror_confirm_k"].asInt,
        )

        val clips = root.getAsJsonArray("clips")
        assertTrue("no golden clips", clips.size() > 0)

        var worstDiff = 0f
        for (ci in 0 until clips.size()) {
            val clip = clips[ci].asJsonObject
            val id = clip["clip_id"].asString
            val onset = clip["onset"].asInt
            val release = clip["release"].asInt
            val hands = frames(floats(clip.getAsJsonObject("hands_image").getAsJsonArray("data")), 126)
            val pose = frames(floats(clip.getAsJsonObject("pose_image").getAsJsonArray("data")), 132)
            val expected = clipFeaturesCausal(hands, pose, onset, release, cfg, ccfg)

            val session = SessionNormalizer(cfg, ccfg).also { it.handedness = Handedness.AUTO }
            val actual = ArrayList<FloatArray>(expected.size)
            for (t in onset..release) {
                session.update(pose[t])
                actual.add(session.feature(pose[t], hands[t]))
            }
            assertEquals("[$id] session frame count", expected.size, actual.size)
            for (t in expected.indices) {
                for (k in 0 until 258) {
                    val d = abs(actual[t][k] - expected[t][k])
                    if (d > worstDiff) worstDiff = d
                    assertTrue(
                        "[$id] session feature diff $d > $tol at frame $t chan $k " +
                            "(session=${actual[t][k]} causal=${expected[t][k]})",
                        d <= tol,
                    )
                }
            }
        }
        println("session S4 parity test: ${clips.size()} clips, worst |Session-Causal| = $worstDiff (tol=$tol)")
    }
}

