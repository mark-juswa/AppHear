"""Export the Kotlin confirm-boundary parity fixture from the Python research decoder.

S2 = Arm A e10 (Keras probabilities; device TFLite argmax parity is 0/669 mismatches). Streams:
the reviewed phone sessions (4 Tier-2 + shadow 023004Z + shadow 022535Z) and the first 40 CAL
streams (more consecutive-sign boundaries). For each stream the observation rows (timestamp, argmax,
P(POST)) and the events of the reference replay under BASELINE and CONFIRM_BOUNDARY_70
(PRE_OR_POST re-arm, exact Android commit recovery), as
android/app/src/test/resources/recognition_v3_experimental/confirm_boundary_parity.tsv.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from eval.runtime_diagnostics import event_reliability as er  # noqa: E402
from eval.runtime_diagnostics import s2_r3_context_suite as suite  # noqa: E402
from eval.runtime_diagnostics import s2_r3_train  # noqa: E402

E = Path("F:/ASL DATASET/5. Apphear3")
OUT = ROOT / "android/app/src/test/resources/recognition_v3_experimental/confirm_boundary_parity.tsv"
DECODERS = ("BASELINE", "CONFIRM_BOUNDARY_70")


def main() -> None:
    pkg = er.load_s2(E, "ARM_A_E10")
    streams: list[tuple[str, np.ndarray, np.ndarray]] = []
    for name, s in er.phone_sessions(E).items():
        streams.append((name, s["timestamps_ms"], pkg.probabilities(s["features"])))
    cal = s2_r3_train.build_dataset(E, suite.read_json(s2_r3_train.CONFIG_PATH))["cal_streams"]
    for k, s in enumerate(cal[:40]):
        streams.append((f"CAL_{k:03d}", s["timestamps_ms"], pkg.probabilities(s["features"])))
    lines = [
        "# Arm A e10 confirm-boundary parity fixture (generated by deploy/export_confirm_boundary_parity_fixture.py)",
        "# O<TAB>stream<TAB>index<TAB>timestamp_ms<TAB>argmax<TAB>p_post",
        "# E<TAB>stream<TAB>decoder<TAB>event_id<TAB>start<TAB>end<TAB>terminal_post<TAB>commit",
    ]
    totals = {d: 0 for d in DECODERS}
    for name, t, p in streams:
        states = np.argmax(p, axis=1)
        for i in range(len(t)):
            lines.append(f"O\t{name}\t{i}\t{float(t[i])!r}\t{int(states[i])}\t{float(p[i, 2])!r}")
        for dec in DECODERS:
            for k, e in enumerate(er.replay_events(p, t, dec), start=1):
                totals[dec] += 1
                lines.append(
                    f"E\t{name}\t{dec}\t{k}\t{int(e['logical_active_start_index'])}\t"
                    f"{int(e['logical_active_end_index'])}\t{int(e['first_post_index'])}\t"
                    f"{int(e['emitted_at_index'])}"
                )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(OUT, len(streams), "streams", totals)


if __name__ == "__main__":
    main()
